# المطابقة باستخدام GPT
def match_summary_with_article(article, summary):
    matching_prompt = ChatPromptTemplate.from_messages([
        SystemMessage(
            content="أنت مساعد ذكي. مهمتك: ربط كل جملة في الملخص بجملة أو أكثر من النص الأصلي. أرجع الناتج JSON بدون شرح إضافي."
        ),
        HumanMessagePromptTemplate.from_template("""
الملخص:
{summary}

النص الأصلي:
{article}

صيغة الإخراج المطلوبة:
[
  {{"summary_sentence": "ملخص الجملة", "article_sentences": ["جملة أو أكثر من النص الأصلي"]}},
  ...
]
""")
    ])

    chain = LLMChain(llm=llm, prompt=matching_prompt)
    output = chain.run(article=article, summary=summary)
    try:
        parsed_output = json.loads(re.search(r'\[.*\]', output, re.DOTALL).group(0))
        return parsed_output
    except:
        return []

