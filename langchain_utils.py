def highlight_summary_and_article(article, summary, matches):
    colors = generate_distinct_colors(len(matches))
    highlighted_article = article
    highlighted_summary = summary
    for idx, match in enumerate(matches):
        color = colors[idx]
        highlighted_summary = highlight_text(highlighted_summary, [match["summary_sentence"]], color)
        for sent in match["article_sentences"]:
            highlighted_article = highlight_text(highlighted_article, [sent], color)
    return highlighted_summary, highlighted_article
